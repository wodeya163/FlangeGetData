FIELDS = ['D', 'K', 'L', 'n', 'Th', 'C', 'H', 'N_A']


def norm(v):
    s = str(v).strip()
    try:
        f = float(s)
        return str(int(f)) if f == int(f) else str(f)
    except ValueError:
        return s


def main():
    fail = 0
    total = 0
    for fam, (samples, src) in SAMPLES.items():
        path = os.path.join(DATA, 'GBT9124_2_' + fam + '.csv')
        rows = {}
        with open(path, encoding='utf-8-sig', newline='') as fh:
            for r in csv.DictReader(fh):
                if r['Class'] == '150':
                    rows[r['DN']] = r
        print('\n=== %s（%s）' % (fam, src))
        fam_fail = fail
        for dn, expected in samples.items():
            row = rows.get(dn)
            if row is None:
                print('  DN%s CSV 缺失' % dn)
                fail += 1
                continue
            for field, exp in zip(FIELDS, expected):
                if exp == '-':
                    continue
                total += 1
                got = norm(row.get(field, ''))
                if got != norm(exp):
                    print('  DN%-4s %-4s CSV=%-8s PDF=%s'
                          % (dn, field, got, exp))
                    fail += 1
        print('  抽样 %d 规格，%s'
              % (len(samples),
                 '全部一致' if fail == fam_fail else '存在差异（见上）'))
    print('\n抽样核对字段数：%d，差异数：%d' % (total, fail))
    return 1 if fail else 0


if __name__ == '__main__':
    sys.exit(main())
