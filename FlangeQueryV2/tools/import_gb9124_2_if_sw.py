def write(name, header, rows):
    path = os.path.join(ROOT, 'Data', name)
    with open(path, 'w', encoding='utf-8', newline='') as fh:
        writer = csv.writer(fh)
        writer.writerow(header)
        writer.writerows(rows)
    print('written', path, len(rows))


