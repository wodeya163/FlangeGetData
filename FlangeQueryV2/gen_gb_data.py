def load_sch():
    """读现有壁厚表 → {DN: {col: val}}"""
    rows = list(csv.reader(io.open(SRC, encoding='utf-8-sig')))
    head = [h.strip() for h in rows[0]]
    out = {}
    for r in rows[1:]:
        if len(r) != len(head):
            continue
        d = dict(zip(head, r))
        try:
            dn = int(d['DN'])
        except (KeyError, ValueError):
            continue
        out[dn] = d
    return head, out


def write(name, header, rows):
    p = os.path.join(DATA, name)
    with open(p, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)
    print('%-40s %d rows' % (name, len(rows)))


def main():
    head, sch = load_sch()
    sch_cols = [h for h in head if h.startswith('Sch') or h in
                ('STD', 'XS', 'XXS')]

    # ---- 1. 90°/45°/180° 弯头
    rows = []
    for dn, nps, da, db in BASE:
        e = ELBOW.get(dn)
        if not e:
            continue
        h45, f90, f90s, p180, k180, a180, a180s = e
        rows.append([dn, nps, da, db or '-', h45, f90, f90s or '-',
                     p180 or '-', k180 or '-', a180 or '-', a180s or '-'])
    write('GB12459_弯头.csv',
          ['DN', 'DN2', 'D_o_A', 'D_o_B', 'H_45', 'F_90LR', 'F_90SR',
           'P_180LR', 'K_180SR', 'A_180LR', 'A_180SR'], rows)

    # ---- 2. 等径三通 / 四通
    rows = []
    for dn, nps, da, db in BASE:
        c = TEE.get(dn)
        if not c:
            continue
        rows.append([dn, nps, da, db or '-', c])
    write('GB12459_三通.csv', ['DN', 'DN2', 'D_o_A', 'D_o_B', 'C'], rows)

    # ---- 3. 异径管（同心/偏心共用尺寸）
    bmap = {dn: (nps, da, db) for dn, nps, da, db in BASE}
    rows = []
    for (d1, d2), h in sorted(REDUCER.items()):
        if d1 not in bmap or d2 not in bmap:
            continue
        n1, a1, bb1 = bmap[d1]
        n2, a2, bb2 = bmap[d2]
        rows.append([d1, n1, a1, bb1 or '-', d2, n2, a2, bb2 or '-', h])
    write('GB12459_异径管.csv',
          ['DN', 'DN2', 'D_o_A', 'D_o_B', 'DN_s', 'DN2_s', 'D_o_A_s',
           'D_o_B_s', 'H'], rows)

    # ---- 4. 管帽
    rows = []
    for dn, nps, da, db in BASE:
        c = CAP.get(dn)
        if not c:
            continue
        e, e1, tlim = c
        rows.append([dn, nps, da, db or '-', e, e1 or '-', tlim or '-'])
    write('GB12459_管帽.csv',
          ['DN', 'DN2', 'D_o_A', 'D_o_B', 'E', 'E1', 'T_lim'], rows)

    # ---- 5. GB 钢管系列（壁厚表 + GB/T 8163 / 3091 / 14976 归属）
    rows = []
    for dn, nps, da, db in BASE:
        s = sch.get(dn)
        if not s:
            continue
        rows.append([dn, nps, da] + [s.get(c, '-') for c in sch_cols])
    write('GB17395_钢管系列.csv', ['DN', 'DN2', 'D_o'] + sch_cols, rows)

    print('\n壁厚列：', sch_cols)


if __name__ == '__main__':
    main()
