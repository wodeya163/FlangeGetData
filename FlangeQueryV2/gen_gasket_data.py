# 统一列定义
COLS = ['标准', 'DN', 'DN2', 'PN', 'Class', '型式', 'D1', 'D2', 'D3', 'T', 'b',
        'P', 'A', 'H', 'B', 'C', 'r']


def blank_row(std):
    """返回一个所有尺寸列为空串、仅填‘标准’的字典。"""
    r = {c: '' for c in COLS}
    r['标准'] = std
    return r


def mk(std, **kw):
    r = blank_row(std)
    for k, v in kw.items():
        r[k] = v
    return r


