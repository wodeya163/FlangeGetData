def get_Rm(material, d):
    '''按直径查 Rm（单位 MPa），无精确区间时相邻线性插值。'''
    ranges = material['ranges']
    for dmin, dmax, rm in ranges:
        if dmin - 1e-09 <= d <= dmax + 1e-09:
            return rm
    if d < ranges[0][0]:
        return ranges[0][2]
    if d > ranges[-1][1]:
        return ranges[-1][2]
    pts = []
    for dmin, dmax, rm in ranges:
        pts.append(((dmin + dmax) / 2, rm))
    pts.sort()
    for i in range(len(pts) - 1):
        x0, y0 = pts[i]
        x1, y1 = pts[i + 1]
        if x0 <= d <= x1:
            return y0 + (y1 - y0) * (d - x0) / (x1 - x0)
    return pts[-1][1]

def recommend_C(d):
    '''按表 7 推荐旋绕比 C 范围。'''
    for dmax, cmin, cmax in SPRING_INDEX_TABLE:
        if d <= dmax:
            return (cmin, cmax)
    return (4, 16)

def allowable_stress(material_kind, spring_type, load_type, use_high=True):
    '''
    返回许用应力系数或固定值。
    spring_type: "torsion" 或 "bending"（扭转弹簧用弯曲）
    load_type: "static"/"finite"/"infinite"/"test"
    use_high: 动负荷范围取上限或下限
    '''
    coeff = ALLOWABLE_COEFF[material_kind][spring_type][load_type]
    if isinstance(coeff, tuple):
        return coeff[1] if use_high else coeff[0]
    return coeff

