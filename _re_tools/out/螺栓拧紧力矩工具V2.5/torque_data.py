def calc_fine_thread_torque(grade, size_str, bolt_type='hex'):
    """计算细牙螺纹力矩（2026-09-26 模型修正）
    依据: T = K·F·d, F = 0.7·σy·As —— 同 K、同 σy、同公称直径 d 下
    T_fine / T_coarse = As_fine / As_coarse = [(d-0.9382·p_fine)/(d-0.9382·p_coarse)]²
    细牙螺距小 → As 更大 → 细牙力矩应略高于粗牙(+5%~19%)。
    旧版按螺距比(p_fine/p_coarse)估算, 系统性低估 15%~50%, 有欠拧松脱风险, 已修正。
    bolt_type: 'hex' 用外六角粗牙基准, 'socket' 用内六角粗牙基准
    """
    import re
    import math
    m = re.match('M(\\d+)×([\\d.]+)', size_str)
    if not m:
        return (None, None, None)
    d = int(m.group(1))
    fine_pitch = float(m.group(2))
    coarse_size = f'''M{d}'''
    t_std = get_torque(bolt_type, coarse_size, grade)
    if not t_std[0] is not None:
        return (None, None, None)
    p_coarse = _coarse_pitch(d)
    if not p_coarse or p_coarse <= 0:
        return (None, None, None)
    as_fine = (math.pi / 4) * (d - 0.9382 * fine_pitch) ** 2
    as_coarse = (math.pi / 4) * (d - 0.9382 * p_coarse) ** 2
    ratio = as_fine / as_coarse
    vmin = round(t_std[0] * ratio, 1)
    vrec = round(t_std[1] * ratio, 1)
    vmax = round(t_std[2] * ratio, 1)
    return (vmin, vrec, vmax)
def calc_torque_from_sigma(sigma_y, size_str, k=0.2):
    '''按任意屈服强度计算力矩（V2.2 自定义材料用）。
    T = K·F·d, F = 0.65·σy·As, As = π/4·((d2+d3)/2)² (精确中径式, 与底账同模型)。
    size_str 支持 粗牙 M12 / 细牙 M12×1.5。返回 (min, rec, max) N·m。
    区间比 0.85/1.15 与底账表风格一致。'''
    import re
    import math
    if not sigma_y or sigma_y <= 0:
        return (None, None, None)
    m = re.match('M(\\d+)(?:×([\\d.]+))?', size_str)
    if not m:
        return (None, None, None)
    d = int(m.group(1))
    p = float(m.group(2)) if m.group(2) else _coarse_pitch(d)
    if not p or p <= 0:
        return (None, None, None)
    d2 = d - 0.6495 * p
    d3 = d - 1.2267 * p
    As = (math.pi / 4) * ((d2 + d3) / 2) ** 2
    F = 0.65 * sigma_y * As
    rec = round(k * F * d / 1000, 1)
    return (round(rec * 0.85, 1), rec, round(rec * 1.15, 1))
def apply_scenario(t, scenario):
    '''应用场景系数'''
    if scenario not in SCENARIOS:
        return None
    f = SCENARIOS[scenario]['factor']
    note = SCENARIOS[scenario]['note']
    vmin = round(t[0] * f[0], 1)
    vrec = round(t[1] * f[1], 1)
    vmax = round(t[2] * f[2], 1)
    return (vmin, vrec, vmax, note)

