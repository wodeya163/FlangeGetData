def estimate_torque(grade, d, k):
    '''经验公式估算力矩 T = K * 0.65 * sigma_y * As (与查表同一物理模型)'''
    sigma_y = YIELD_STRENGTH.get(grade)
    if not sigma_y is not None:
        return None
    import math
    p = _coarse_pitch(d)
    if not p:
        return None
    d2 = d - 0.6495 * p
    d3 = d - 1.2267 * p
    As = (math.pi / 4) * ((d2 + d3) / 2) ** 2
    F = 0.65 * sigma_y * As
    T = k * F * d / 1000
    return round(T, 1)
